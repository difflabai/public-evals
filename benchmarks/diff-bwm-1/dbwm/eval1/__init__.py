"""Eval 1: one company, commit a six-quarter operating plan.

The agent gets one synthetic operating company (goal: grow revenue to a target
multiple of the plan's own period-0 value by period 5; constraints on burn,
cash, gross margin and hiring; a handful of levers with their defaults; the
do-nothing trajectory) and must commit plan.json (lever bindings) and
claims.json (does the plan hit the goal and every constraint, and what final
revenue it projects). Scoring is exact and judge-free: the deterministic
company model evaluates the plan. Arms differ ONLY in access to that model
through the ``run_model`` oracle tool and the channel it reports on (arms.py).

Package layout
    engine.py          the company evaluator, constraint check and goal multiple
                       (paper oracle.py, verbatim; Python engine is normative)
    score.py           rulesets ``paper`` (score_plan, bit for bit) and ``v1``
    claims.py          paper and strict readings of claims.json (via dbwm.core.claims)
    oracle_tool.py     the run_model oracle: sealed modes numeric|prose|raw|broken
    arms.py            ArmSpecs (tool policies, sealed modes, readonly query budget)
    prompt.py          the corrected-prompt text (verbatim) + the original-prompt variant
    brief.py           task briefs (data/eval1/tasks, regenerated byte-identically)
    gen/               world + calibration generator (scorer side; embeds the answer key)
    stub_agent.py      deterministic LLM-free agent for every arm
    paper_report.py    the paper's report.py aggregation, bootstrap, decision rule and HTML
    report.py          eval-1 report over a dbwm run (paper aggregation + both denominators)
    selftest.py        selftest(): calibration, briefs, generator, oracle modes, stub agent
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Callable

from dbwm.core.types import (
    DEFAULT_EVAL_RULESETS,
    Cell,
    CheckResult,
    RegimeConfig,
    ScoreResult,
    StagingManifest)

from . import _paths
from .arms import ARM_ORDER, ORACLE_MODE, RUN_MODEL, build_arms, load_regime_defaults
from .brief import USED_COMPANIES, load_brief
from .engine import load_calibration, load_model_and_tiers
from .oracle_tool import run_model
from .prompt import build_prompt
from .score import DELIVERABLES, TIERS, score_submission, split_instance

EVAL_ID = "eval1"

# The 15 cells of the paper's design (default instance set): 5 companies x 3 tiers.
PUBLISHED_INSTANCES = tuple(f"{c}__{t}" for c in USED_COMPANIES for t in TIERS)

# Names an agent has no business touching (audit (a)): the core defaults plus
# eval 1's world, calibration and paper-tool files.
SCORER_ONLY_NAMES = (
    "reference.json", "world.json", "ANSWER_KEY", "checks.jsonl", "answer_key", "grader", "private",
    "operating-model.json", "eval-tiers.json", "scenarios.json", "calibration",
    "bwm-scenario-matrix", "bwm-scenario-matrix-calibration", "generate_matrix.py",
    "generate-bwm-scenario-matrix.py", "bwm_query.py", "oracle.py", "CANARY.txt")

_PKG_DIR = Path(__file__).resolve().parent
# Scorer sources hashed into every verdict's engine_hash.
ENGINE_SOURCES = tuple(_PKG_DIR / f for f in ("engine.py", "score.py", "claims.py", "oracle_tool.py")) + (
    _PKG_DIR.parent / "core" / "claims.py",)


def engine_hash() -> str:
    import os

    from dbwm.core.verdict import engine_hash as _eh

    files = sorted(p.resolve() for p in ENGINE_SOURCES)
    return _eh(files, root=Path(os.path.commonpath([str(p.parent) for p in files])))


def all_instances() -> list[str]:
    """Every shipped (company, tier): 10 companies x 3 tiers (data/eval1/tasks)."""
    out = []
    for p in sorted(_paths.data("tasks").glob("*.json")):
        try:
            split_instance(p.stem)
        except ValueError:
            continue
        out.append(p.stem)
    return out


def _canon_sha(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":"),
                                     ensure_ascii=False).encode("utf-8")).hexdigest()


def _nontrivial_plan(bindings: Any) -> bool:
    """A plan worth treating as a fingerprint: >= 2 levers bound and some series not flat."""
    if not isinstance(bindings, dict) or len(bindings) < 2:
        return False
    for v in bindings.values():
        if isinstance(v, dict):
            v = v.get("values")
        if isinstance(v, list) and len({str(x) for x in v}) > 1:
            return True
    return False


class Eval1:
    """The ``EVAL`` object (satisfies :class:`dbwm.core.types.EvalDef`)."""

    eval_id = EVAL_ID
    title = "Single company: commit a six-quarter operating plan to a deterministic company model"
    deliverables = DELIVERABLES
    SCORER_ONLY_NAMES = SCORER_ONLY_NAMES
    ENGINE_SOURCES = ENGINE_SOURCES

    def __init__(self) -> None:
        self.arms = build_arms()

    # -- design ---------------------------------------------------------------
    def instances(self) -> list[str]:
        """The default instance set: the paper's 15 (company, tier) cells."""
        return list(PUBLISHED_INSTANCES)

    def default_regime(self) -> dict[str, Any]:
        return load_regime_defaults()

    def cells(self, regime: RegimeConfig) -> list[Cell]:
        instances = list(regime.instances) if regime.instances else self.instances()
        known = set(all_instances())
        unknown_i = [i for i in instances if i not in known]
        if unknown_i:
            raise ValueError(f"unknown eval1 instance(s) {unknown_i}; known: {sorted(known)}")
        unknown_a = [a for a in regime.arms if a not in self.arms]
        if unknown_a:
            raise ValueError(f"unknown eval1 arm(s) {unknown_a}; known: {list(ARM_ORDER)}")
        if regime.reps < 1:
            raise ValueError("reps must be >= 1")
        return [Cell(EVAL_ID, i, a, r) for r in range(regime.reps) for i in instances for a in regime.arms]

    def _check_cell(self, cell: Cell) -> None:
        split_instance(cell.instance)
        if not _paths.data("tasks", f"{cell.instance}.json").is_file():
            raise ValueError(f"unknown eval1 instance {cell.instance!r}")
        if cell.arm not in self.arms:
            raise ValueError(f"unknown eval1 arm {cell.arm!r}")

    # -- what the agent sees --------------------------------------------------
    def stage(self, cell: Cell) -> StagingManifest:
        """TASK.md (the prompt) and nothing else.

        The paper gave agents only the prompt too, but ran them inside the
        harness checkout next to the oracle, the worlds, the calibration
        answer key and sibling trials. No brief file is staged:
        everything in the brief is already in the prompt, as in the paper.
        """
        self._check_cell(cell)
        return StagingManifest(files=[], task_md=self.prompt(cell), writable_dirs=[])

    def prompt(self, cell: Cell) -> str:
        self._check_cell(cell)
        arm = self.arms[cell.arm]
        transport = arm.tools.transport if arm.tools.oracle_tools else None
        return build_prompt(load_brief(cell.instance), cell.arm, transport=transport,
                            query_budget=arm.query_budget)

    def oracle_handlers(self, cell: Cell) -> dict[str, Callable]:
        self._check_cell(cell)
        if ORACLE_MODE[cell.arm] is None:
            return {}
        return {RUN_MODEL.name: run_model}

    # -- scoring --------------------------------------------------------------
    def score(self, deliverables_dir: Path, cell: Cell, ruleset: str) -> ScoreResult:
        self._check_cell(cell)
        if ruleset not in DEFAULT_EVAL_RULESETS:  # paper and v1; no "as-run" (core RULESETS, eval 5 only)
            raise ValueError(f"unknown ruleset {ruleset!r}")
        _verdict, result = score_submission(Path(deliverables_dir), cell.instance, cell.arm,
                                            cell.rep, ruleset)
        return result

    def answer_key_values(self, cell: Cell) -> list[str]:
        """Strings only the scorer-side files hold, >= 8 characters, absent from public text.

        Listed: the calibration report's 50-digit statistics of the naive and
        careful reference plans for this company (goal multiple, max burn, min
        cash, min margin) and the world's private registry reference. An honest
        agent cannot write these without reading private/eval1 (if it runs the
        careful plan through run_model, the oracle output explains the value and
        the audit only notes it). NOT listed: reference-plan lever values and
        hidden leaf parameters, which are round numbers an agent may well pick
        itself (audit doc: never list achievable values). Anything that also
        occurs in the brief or in any arm's prompt for this instance is dropped.
        """
        self._check_cell(cell)
        company, _tier = split_instance(cell.instance)
        vals: set[str] = set()
        for entry in load_calibration():
            if entry.get("model_id") != company:
                continue
            for plan in ("naive", "careful"):
                for v in (entry.get("stats", {}).get(plan) or {}).values():
                    vals.add(str(v))
        _model, tiers_doc = load_model_and_tiers(company)
        if tiers_doc.get("registry_ref"):
            vals.add(str(tiers_doc["registry_ref"]))
        public = self._public_text(cell.instance)
        return sorted(v for v in vals if len(v) >= 8 and v not in public)

    def _public_text(self, instance: str) -> str:
        parts = [_paths.data("tasks", f"{instance}.json").read_text(encoding="utf-8"),
                 _paths.data("tasks", f"{instance}.md").read_text(encoding="utf-8")]
        for arm in self.arms:
            parts.append(self.prompt(Cell(EVAL_ID, instance, arm, 0)))
        return "\n".join(parts)

    def duplicate_corpus(self, cell: Cell) -> list[str]:
        """Canonical sha256s a deliverable must not equal (audit (c)).

        The calibration naive/careful reference plans (the private answer key)
        in both accepted plan shapes, when non-trivial (>= 2 levers bound, some
        series not flat): a simple plan is something an honest agent can write
        independently, and a false duplicate flag would exclude an honest cell.
        """
        self._check_cell(cell)
        company, _tier = split_instance(cell.instance)
        hashes: set[str] = set()
        for entry in load_calibration():
            if entry.get("model_id") != company:
                continue
            for plan in (entry.get("reference_plans") or {}).values():
                if _nontrivial_plan(plan):
                    hashes.add(_canon_sha(plan))
                    hashes.add(_canon_sha({"bindings": plan}))
        return sorted(hashes)

    # -- agents, reports, checks ----------------------------------------------
    def stub_agent(self, cell: Cell, sandbox: Path, call_oracle: Callable[[str, dict], Any]) -> None:
        """Deterministic, LLM-free agent: reads TASK.md, calls run_model, writes deliverables."""
        self._check_cell(cell)
        from .stub_agent import run_stub

        sandbox = Path(sandbox)
        task = (sandbox / "TASK.md").read_text(encoding="utf-8")
        run_stub(task, cell.arm, cell.cell_id, sandbox, call_oracle)

    def report(self, run_dir: Path) -> dict[str, Any]:
        from .report import build_eval1_report

        return build_eval1_report(Path(run_dir))

    def selftest(self) -> list[CheckResult]:
        from .selftest import selftest

        return selftest()

    def engine_sources(self) -> list[Path]:
        return list(ENGINE_SOURCES)

    def engine_hash(self) -> str:
        return engine_hash()


EVAL = Eval1()


