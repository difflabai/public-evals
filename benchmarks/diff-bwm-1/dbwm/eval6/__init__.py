"""Eval 6: epistemic access. Does a calibrated model carrying information the history cannot contain help?

D1 (agent eval). Each world is a four-segment subscription business (one hub,
three spokes) driven by unobserved AR(1) demand; the 72-quarter history was
generated by a policy that co-moves every lever with the shared demand factor,
so the sign of the hub -> spoke marketing spillover is not identified by it.
The agent commits a constant per-segment marketing level and price multiplier
for the next 8 quarters (plan.json) plus a profit projection (claims.json). A
Monte-Carlo oracle with the true parameters scores the plan after the attempt.

  unaided  public/history.csv, public/task.json, the brief; bash + python.
  aided    the same plus a seed-free fitted model (correct coupling and price
           signs, ~8%-noised magnitudes, latent nowcast) and its simulator
           (model_sim.py + heldout_sim.py).

Headline: aided-minus-unaided realized-profit uplift per world, world-clustered
bootstrap, reported under both no-plan policies (dbwm.eval6.contrast).

D2 (no agent sandbox): a reward-signal rank-off on 16 mid-game states; offline
mechanical signals (d2_signals) and an LLM judge (d2_judge) are compared by
Kendall tau-b against the true value V*. Exposed as ``dbwm eval6-d2``.

D3 (dispersion pilot, gate only; self-supply only; not pooled with D1):
``dbwm.eval6.d3`` holds the offline port of the pilot's scorer (the pilot's
references, defect included, and v1 engine-consistent references) and a
separate, non-canonical runnable EVAL (``dbwm run --eval dbwm.eval6.d3``). It
is not part of this EVAL and not in SCORER_SOURCES.

Modules: latent_engine (true dynamics, scorer side), gen/ (world generator with
--seed-salt, fitted model v1/v2, step-0 certification), score_d1 (paper/v1
rulesets; v1 bounds marketing at the history's per-segment maximum), contrast,
d2_signals, d2_judge, d2_report, prompt (paper and v1 briefs), arms, stub_agent,
report, d3/.
Card: docs/evals/eval6.md. Changes vs the paper instrument: see the eval card.

Importing this package does not import numpy; only scoring, staging checks of
the aided simulator, generation and D2 do.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import re
import tempfile
from pathlib import Path
from typing import Any, Callable

from dbwm.core.types import (CANARY_GUID, RULESET_PAPER, RULESET_V1, Cell, CheckResult, RegimeConfig,
                             ScoreResult, StagingManifest)

from . import _paths
from .arms import ARMS, list_instances, manifest
from .prompt import brief, disclosed_values, world_accounting

# Scorer-only names: a tool_use input naming one of these as a path segment is an
# audit finding (dbwm.core.audit). The core defaults plus eval 6's own: the answer
# key files, the paper's leaky fitted model, the certify scan, the scoring seeds,
# the D2 offline report (V*), and the scorer-side modules that regenerate answer
# keys or compute V* (the paper staged latent_engine.py into the aided sandbox).
SCORER_ONLY_NAMES = (
    "reference.json", "world.json", "ANSWER_KEY", "checks.jsonl", "answer_key", "grader", "private",
    "theta.json", "mstar.json", "AIDED_v1", "certify_scan.json", "scoring_seeds.json",
    "d2-offline-signals.json", "d2_offline_n16.json", "latent_engine.py", "make_latent_world.py",
    "certify_world.py", "make_fitted_model.py", "d2_signals.py", "CANARY.txt")

DELIVERABLES = ("plan.json", "claims.json")
_HOST_PATH = re.compile(r"/(?:Users|home|private/var|var/folders)/")
# Files whose bytes define the scorer (hashed into every verdict as engine_hash).
SCORER_SOURCES = ("latent_engine.py", "score_d1.py", "_paths.py")


def _task(world_id: str) -> dict:
    return json.loads(_paths.world_public(world_id, "task.json").read_text())


class Eval6:
    eval_id = "eval6"
    title = "Epistemic access: a calibrated model vs a confounded history (D1)"
    arms = ARMS
    deliverables = DELIVERABLES

    # -- design ----------------------------------------------------------------------

    def instances(self) -> list[str]:
        return list_instances()

    def default_regime(self) -> dict[str, Any]:
        try:
            from dbwm.core.regime import load_regime_json
            return load_regime_json(self.eval_id)
        except Exception:  # noqa: BLE001 - core regime helper optional here
            return json.loads((Path(__file__).with_name("regime.json")).read_text())

    def cells(self, regime: RegimeConfig) -> list[Cell]:
        known = self.instances()
        insts = list(regime.instances) if regime.instances else known
        arms = list(regime.arms) if regime.arms else list(ARMS)
        for i in insts:
            if i not in known:
                raise ValueError(f"eval6: unknown instance {i!r}; choose from {known}")
        for a in arms:
            if a not in ARMS:
                raise ValueError(f"eval6: unknown arm {a!r}; choose from {list(ARMS)}")
        return [Cell(self.eval_id, i, a, r) for r in range(regime.reps) for i in insts for a in arms]

    def _check_cell(self, cell: Cell) -> None:
        if cell.arm not in ARMS or not _paths.world_public(cell.instance, "task.json").is_file():
            raise ValueError(f"eval6: bad cell {cell}")

    def engine_sources(self) -> list[Path]:
        here = Path(__file__).resolve().parent
        return [here / n for n in SCORER_SOURCES] + [here.parent / "core" / "claims.py"]

    # -- sandbox ---------------------------------------------------------------------

    def stage(self, cell: Cell) -> StagingManifest:
        """Agent-visible files only: public/history.csv, public/task.json (+ fitted_model.json,
        model_sim.py, heldout_sim.py for the aided arm). TASK.md is the v1 brief (the paper text plus
        the pinned profit accounting and the per-segment marketing bound; prompt.py)."""
        self._check_cell(cell)
        return manifest(cell.instance, cell.arm, self.prompt(cell))

    def prompt(self, cell: Cell) -> str:
        """The paper passed the full brief as the first prompt; so does this (v1 brief)."""
        self._check_cell(cell)
        return brief(_task(cell.instance), cell.arm, world_accounting(cell.instance))

    def disclosed_values_for(self, cell: Cell) -> list[str]:
        """Values the v1 brief discloses on purpose (rounded gm / fixed, marketing bounds): the core
        pre-check and audit never count an answer-key value occurring only inside one as a leak."""
        self._check_cell(cell)
        return disclosed_values(world_accounting(cell.instance))

    def oracle_handlers(self, cell: Cell) -> dict:
        """Eval 6 serves no tools: the unaided arm has only bash, and the aided arm's
        simulator is its own fitted model, run inside the sandbox as in the paper. The
        true-dynamics oracle scores the plan after the attempt and is never queryable."""
        self._check_cell(cell)
        return {}

    # -- scoring ---------------------------------------------------------------------

    def score(self, deliverables_dir: Path, cell: Cell, ruleset: str) -> ScoreResult:
        from .score_d1 import score_result
        self._check_cell(cell)
        return score_result(Path(deliverables_dir), cell.instance, ruleset)

    def answer_key_values(self, cell: Cell) -> list[str]:
        from .score_d1 import answer_key_values
        self._check_cell(cell)
        return answer_key_values(cell.instance, disclosed=self.disclosed_values_for(cell))

    def stub_agent(self, cell: Cell, sandbox: Path, call_oracle: Callable[[str, dict], Any]) -> None:
        from .stub_agent import stub_agent
        self._check_cell(cell)
        stub_agent(cell, Path(sandbox), call_oracle)

    def report(self, run_dir: Path) -> dict[str, Any]:
        from .report import report
        return report(run_dir)

    def report_markdown(self, rep: dict[str, Any]) -> str:
        """report.md's eval section: core prints the generic tables itself, so they are left out here."""
        from .report import render_markdown
        return render_markdown(rep, include_core=False)

    # -- self test -------------------------------------------------------------------

    def selftest(self) -> list[CheckResult]:
        return selftest(self)


EVAL = Eval6()


def selftest(ev: Eval6 = EVAL) -> list[CheckResult]:
    """Fast offline checks (about 10 s). Missing fixtures fail; optional dependencies that
    are absent are reported as SKIPPED with the reason, never as ok."""
    out: list[CheckResult] = []
    try:
        import numpy  # noqa: F401
        have_np = True
        out.append(CheckResult("numpy", True, f"numpy {numpy.__version__} importable (eval6 extra)"))
    except ImportError:
        have_np = False
        out.append(CheckResult("numpy", False, "numpy missing: install the eval6 extra "
                               "(pip install 'diff-bwm-1[eval6]'); numpy-dependent checks skipped", skipped=True))
    canary = _paths.private("CANARY.txt")
    out.append(CheckResult("canary", canary.is_file() and CANARY_GUID in canary.read_text(),
                           "private/eval6/CANARY.txt carries the canary GUID"))
    worlds = list_instances()
    missing = []
    for w in worlds:
        for p in (_paths.world_public(w, "history.csv"), _paths.world_public(w, "task.json"),
                  _paths.world_aided_v2(w), _paths.world_aided_v1(w), _paths.answer_key(w, "theta.json"),
                  _paths.answer_key(w, "mstar.json")):
            if not p.is_file():
                missing.append(f"{w}/{p.name}")
    for p in (_paths.certify_scan(), _paths.scoring_seeds(), _paths.aided_tool("model_sim.py"),
              _paths.aided_tool("heldout_sim.py")):
        if not p.is_file():
            missing.append(p.name)
    out.append(CheckResult("fixtures", len(worlds) == 11 and not missing,
                           f"{len(worlds)} worlds; missing: {missing[:5] or 'none'}"))
    seeds = json.loads(_paths.scoring_seeds().read_text()) if _paths.scoring_seeds().is_file() else {}
    sim_seed = None
    ms = _paths.aided_tool("model_sim.py")
    if ms.is_file():
        for line in ms.read_text().splitlines():
            if line.startswith("BASE_SEED"):
                sim_seed = int(line.split("=")[1])
    v1_seed = (seeds.get("v1") or {}).get("base_seed")
    out.append(CheckResult("scoring-seed-sequestered", v1_seed is not None and sim_seed is not None
                           and v1_seed not in (sim_seed, (seeds.get("paper") or {}).get("base_seed")),
                           "v1 scoring seed differs from the staged simulator's and the paper's"))

    # staging leak checks (every arm x instance)
    leaks, checked = [], 0
    if not have_np:
        out.append(CheckResult("staging-leaks", False, "answer-key values need the scorer: numpy missing",
                               skipped=True))
    else:
        for w in worlds:
            for arm in ARMS:
                cell = Cell(ev.eval_id, w, arm, 0)
                m = ev.stage(cell)
                vals = ev.answer_key_values(cell)
                blobs = [(f.dst, f.src.read_bytes() if f.src else f.content) for f in m.files]
                blobs.append(("TASK.md", m.task_md.encode()))
                blobs.append(("<prompt>", ev.prompt(cell).encode()))
                for dst, b in blobs:
                    t = b.decode("utf-8", errors="replace")
                    checked += 1
                    if CANARY_GUID in t:
                        leaks.append(f"{w}/{arm}:{dst}:canary")
                    hit = next((v for v in vals if v in t), None)
                    if hit:
                        leaks.append(f"{w}/{arm}:{dst}:answer-key value")
                    if any(part in SCORER_ONLY_NAMES for part in Path(dst).parts):
                        leaks.append(f"{w}/{arm}:{dst}:scorer-only name")
                    if dst in ("TASK.md", "<prompt>") and (_HOST_PATH.search(t) or ".." in t
                                                           or "private/" in t or "ANSWER_KEY" in t):
                        leaks.append(f"{w}/{arm}:{dst}:path")
                fm = [f for f in m.files if f.dst == "fitted_model.json"]
                if fm and '"seed"' in fm[0].src.read_text():
                    leaks.append(f"{w}/{arm}:fitted_model.json carries a seed")
        out.append(CheckResult("staging-leaks", not leaks,
                               f"{len(worlds)} worlds x {len(ARMS)} arms, {checked} staged texts: no canary, "
                               f"answer-key value, scorer-only name, path or seed" if not leaks
                               else f"leaks: {leaks[:5]}"))

    if have_np:
        # D2 offline selftest (deterministic, oracle-equivalent executor)
        from . import d2_signals as ds
        buf = io.StringIO()
        try:
            with contextlib.redirect_stdout(buf):
                ds.selftest()
            out.append(CheckResult("d2-signals-selftest", True, "D2 offline pipeline deterministic and "
                                   "oracle-equivalent (d2_signals.selftest)"))
        except SystemExit:
            out.append(CheckResult("d2-signals-selftest", False, buf.getvalue()[-400:]))
        # scorer known-good / known-bad on one world, paper ruleset
        from .score_d1 import load_answer_key, score_d1
        with tempfile.TemporaryDirectory(prefix="dbwm_e6self_") as td:
            ak = load_answer_key("w1")
            (Path(td) / "plan.json").write_text(json.dumps({"plan": ak.mstar_plan}))
            d = score_d1(Path(td), "w1", RULESET_PAPER)
            out.append(CheckResult("scorer-mstar-plan", d["gap_to_mstar_pct"] == 0.0,
                                   f"committing M*'s plan scores gap {d['gap_to_mstar_pct']!r} (exactly 0 under CRN)"))
            (Path(td) / "plan.json").unlink()
            d = score_d1(Path(td), "w1", RULESET_PAPER)
            dv = score_d1(Path(td), "w1", RULESET_V1)
            out.append(CheckResult("scorer-no-plan", round(d["gap_to_mstar_pct"], 4) == 19.2749 and d["no_plan"]
                                   and dv["no_plan"] and dv["reached_tau"] is False,
                                   f"no plan.json -> reference-plan score, gap {d['gap_to_mstar_pct']:.4f}% "
                                   f"(paper), flagged no_plan in both rulesets"))
        try:
            import scipy.stats  # noqa: F401
            import random
            from .d2_signals import kendall_tau_b
            rng = random.Random(6)
            worst = 0.0
            for _ in range(200):
                n = rng.randint(2, 9)
                x = [rng.choice([0, 1, 2, 3, rng.random()]) for _ in range(n)]
                y = [rng.choice([0, 1, rng.random()]) for _ in range(n)]
                a = kendall_tau_b(x, y)
                b = float(scipy.stats.kendalltau(x, y)[0])
                if a != a and b != b:
                    continue
                worst = max(worst, abs(a - b))
            out.append(CheckResult("kendall-tau-vs-scipy", worst == 0.0,
                                   f"stdlib tau-b equals scipy.stats.kendalltau on 200 random tied inputs "
                                   f"(max |diff| {worst})"))
        except ImportError as e:
            out.append(CheckResult("kendall-tau-vs-scipy", False,
                                   f"scipy.stats not importable (optional): {str(e).splitlines()[0][:120]}",
                                   skipped=True))
    if have_np:
        # D3 (non-canonical; dbwm.eval6.d3): briefs leak-free, probe-pair rule, stub scored (about 2 s)
        from .d3 import selftest as d3_selftest
        for c in d3_selftest():
            out.append(CheckResult(f"d3-{c.name}", c.ok, c.detail, c.skipped))
    if os.environ.get("DBWM_EVAL6_FULL") == "1" and have_np:
        from . import latent_engine as le
        buf = io.StringIO()
        try:
            with contextlib.redirect_stdout(buf):
                le.selftest()
            out.append(CheckResult("latent-engine-selftest", True, "engine deterministic, confounded, decision-hard"))
        except SystemExit:
            out.append(CheckResult("latent-engine-selftest", False, buf.getvalue()[-400:]))
    else:
        out.append(CheckResult("latent-engine-selftest", False,
                               "slow (~45 s); runs under pytest tests/eval6 or with DBWM_EVAL6_FULL=1", skipped=True))
    return out


