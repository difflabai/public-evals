def _d1_parser(p: argparse.ArgumentParser) -> None:
    from . import contrast
    sub = p.add_subparsers(dest="d1cmd", required=True)
    contrast.configure_parser(sub.add_parser("contrast", help="aided-minus-unaided uplift (both no-plan policies)"))


def _d1_cmd(args: argparse.Namespace) -> int:
    from . import contrast
    return contrast.run(args)


def _d2_parser(p: argparse.ArgumentParser) -> None:
    from . import d2_judge, d2_report, d2_signals
    sub = p.add_subparsers(dest="d2group", required=True)
    d2_signals.configure_parser(sub.add_parser("signals", help="offline rank-off: selftest | run"))
    d2_judge.configure_parser(sub.add_parser("judge", help="LLM judge: run | summary | prompt"))
    d2_report.configure_parser(sub.add_parser("report", help="render a saved offline report"))


def _d2_cmd(args: argparse.Namespace) -> int:
    from . import d2_judge, d2_report, d2_signals
    if args.d2group == "signals":
        return d2_signals.run_cli(args)
    if args.d2group == "judge":
        return d2_judge.run_cli(args)
    return d2_report.run_cli(args)


def _worlds_parser(p: argparse.ArgumentParser) -> None:
    from .gen import certify_world, make_fitted_model, make_latent_world
    sub = p.add_subparsers(dest="wcmd", required=True)
    make_latent_world.configure_parser(sub.add_parser("make", help="generate a world (--seed-salt for a private split)"))
    make_fitted_model.configure_parser(sub.add_parser("fitted", help="build the aided arm's fitted model (v1/v2)"))
    certify_world.configure_parser(sub.add_parser("certify", help="step-0 certification gate"))


def _worlds_cmd(args: argparse.Namespace) -> int:
    from .gen import certify_world, make_fitted_model, make_latent_world
    mod = {"make": make_latent_world, "fitted": make_fitted_model, "certify": certify_world}[args.wcmd]
    return int(mod.run(args) or 0)


